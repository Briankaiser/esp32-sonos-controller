"""
Inject the firmware version into the build.

Runs `git describe --tags --always --dirty` at build time and:
  1. Generates `src/services/fw_version_generated.h` defining OPENSONOS_FW_VERSION
     (a C string literal), which src/services/fw_version.h includes. This is done
     via a generated header rather than a `-D` build flag because appending
     CPPDEFINES from an extra script does not reliably reach the src/ (projenv)
     compilation environment across PlatformIO/SCons versions; a header the
     firmware #includes always compiles in, and only re-triggers the two files
     that use it (content-hashed, so an unchanged version is a no-op rebuild).
  2. Writes the same value to `<build_dir>/fw_version.txt`, a sidecar the
     host-side fleet updater reads so the operator can't mistype the target
     version it waits for after a reboot.

Falls back to "unknown" when git metadata is unavailable (e.g. a source
tarball with no .git), so the reported version is never empty.
"""
Import("env")  # noqa: F821 — injected by PlatformIO/SCons
import os
import subprocess


def _git_describe(project_dir):
    try:
        out = subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=project_dir,
            capture_output=True,
            text=True,
            timeout=10,
        )
        if out.returncode == 0:
            v = out.stdout.strip()
            if v:
                return v
    except (OSError, subprocess.SubprocessError):
        pass
    return "unknown"


def _c_string_escape(v):
    return v.replace("\\", "\\\\").replace('"', '\\"')


def _write_if_changed(path, content):
    # Avoid bumping mtime when the value is unchanged so SCons' content decider
    # does not needlessly rebuild the two TUs that include the header.
    if os.path.isfile(path):
        with open(path) as f:
            if f.read() == content:
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)


project_dir = env.subst("$PROJECT_DIR")
build_dir = env.subst("$BUILD_DIR")
version = _git_describe(project_dir)

# 1. Generated header the firmware includes.
header = (
    "// Auto-generated by extra_scripts/fw_version.py — do not edit, do not commit.\n"
    "#pragma once\n"
    '#define OPENSONOS_FW_VERSION "%s"\n' % _c_string_escape(version)
)
_write_if_changed(os.path.join(project_dir, "src", "services", "fw_version_generated.h"), header)

# 2. Sidecar for the fleet updater — always refreshed, sits next to the .bin.
os.makedirs(build_dir, exist_ok=True)
with open(os.path.join(build_dir, "fw_version.txt"), "w") as f:
    f.write(version + "\n")

# 3. Board sidecar, symmetric with fw_version.txt. The board identifier is the
# PlatformIO env name (compiled into the image via -DOPENSONOS_BOARD_NAME); this
# sidecar lets the fleet updater read the target board without opening the .bin,
# mirroring how fw_version.txt backs the embedded version marker.
board = env.subst("$PIOENV")
with open(os.path.join(build_dir, "fw_board.txt"), "w") as f:
    f.write(board + "\n")

print("INFO [fw_version]: firmware version = %s, board = %s" % (version, board))
